create or replace function public.create_order(p_items jsonb,p_address_id bigint default null,p_payment_method text default null,p_delivery_method text default null)
returns public.orders language plpgsql security definer set search_path=public as $$
declare v_order public.orders; v_item jsonb; v_product public.products; v_qty integer; v_total numeric(14,2):=0;
begin
 if auth.uid() is null then raise exception 'Authentification requise'; end if;
 if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items)=0 then raise exception 'Panier vide'; end if;
 if p_address_id is not null and not exists(select 1 from public.addresses where id=p_address_id and user_id=auth.uid()) then raise exception 'Adresse invalide'; end if;
 insert into public.orders(user_id,address_id,payment_method,delivery_method,total) values(auth.uid(),p_address_id,p_payment_method,p_delivery_method,0) returning * into v_order;
 for v_item in select * from jsonb_array_elements(p_items) loop
   v_qty := (v_item->>'quantity')::integer;
   select * into v_product from public.products where id=(v_item->>'product_id')::bigint for update;
   if not found then raise exception 'Produit introuvable'; end if;
   if v_qty < 1 or v_qty > v_product.stock then raise exception 'Stock insuffisant pour %',v_product.name; end if;
   v_total := v_total + v_product.price * v_qty;
   insert into public.order_items(order_id,product_id,product_name,unit_price,quantity) values(v_order.id,v_product.id,v_product.name,v_product.price,v_qty);
   update public.products set stock=stock-v_qty,updated_at=now() where id=v_product.id;
 end loop;
 update public.orders set total=v_total where id=v_order.id returning * into v_order;
 return v_order;
exception when others then raise;
end; $$;

revoke all on function public.create_order(jsonb,bigint,text,text) from public;
grant execute on function public.create_order(jsonb,bigint,text,text) to authenticated;

