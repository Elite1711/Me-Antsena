create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  first_name text not null default '',
  last_name text not null default '',
  email text not null unique,
  phone text,
  role text not null default 'user' check (role in ('user','admin')),
  status text not null default 'active' check (status in ('active','suspended')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  icon text default '🏷️'
);
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null default '',
  price numeric(14,2) not null check(price >= 0),
  stock integer not null default 0 check(stock >= 0),
  category_id bigint references public.categories(id) on delete set null,
  images jsonb not null default '[]'::jsonb,
  tags jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.addresses (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  label text not null default 'Livraison', street text not null, created_at timestamptz not null default now()
);
create table if not exists public.favorites (
  user_id uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  created_at timestamptz not null default now(), primary key(user_id,product_id)
);
create table if not exists public.interactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  type text not null, value numeric(12,2), created_at timestamptz not null default now()
);
create table if not exists public.recommendations (
  id bigint generated by default as identity primary key,
  type text not null check (type in ('collaborative','content','hybrid')),
  product_id bigint not null references public.products(id) on delete cascade,
  score numeric(12,6) not null default 0,
  created_at timestamptz not null default now(),
  unique(type, product_id)
);
create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  rating integer not null check(rating between 1 and 5), comment text,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(), unique(user_id,product_id)
);
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete restrict,
  address_id bigint references public.addresses(id) on delete set null,
  payment_method text, delivery_method text,
  status text not null default 'pending' check(status in ('pending','paid','shipped','delivered','cancelled')),
  total numeric(14,2) not null default 0, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null, unit_price numeric(14,2) not null, quantity integer not null check(quantity > 0)
);

create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path=public as $$
begin
  insert into public.profiles(id,first_name,last_name,email,phone)
  values(new.id,coalesce(new.raw_user_meta_data->>'first_name',''),coalesce(new.raw_user_meta_data->>'last_name',''),new.email,coalesce(new.raw_user_meta_data->>'phone',''))
  on conflict(id) do update set email=excluded.email;
  return new;
end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.profiles where id=auth.uid() and role='admin' and status='active');
$$;

create or replace function public.admin_set_user_status(p_user_id uuid, p_status text) returns public.profiles
language plpgsql security definer set search_path=public as $$
declare v public.profiles;
begin
  if not public.is_admin() then raise exception 'Accès administrateur requis'; end if;
  if p_status not in ('active','suspended') then raise exception 'Statut invalide'; end if;
  update public.profiles set status=p_status,updated_at=now() where id=p_user_id returning * into v;
  if not found then raise exception 'Utilisateur introuvable'; end if;
  return v;
end; $$;
revoke all on function public.admin_set_user_status(uuid,text) from public;
grant execute on function public.admin_set_user_status(uuid,text) to authenticated;

